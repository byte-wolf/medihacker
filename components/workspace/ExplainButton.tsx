"use client";

import { InlineLoading, InlineNotification, Modal } from "@carbon/react";
import { Information, Launch } from "@carbon/icons-react";
import { useState } from "react";

type Explanation = { why: string; guideline: { title: string; url: string } | null };

// Session-level memo on top of the server cache, so reopening a modal is instant.
const memo = new Map<string, Explanation>();

/** Info button for a briefing item: opens a modal explaining why it matters for this role and situation. */
export function ExplainButton({ situationId, label }: { situationId: number; label: string }) {
  const key = `${situationId}:${label}`;
  const [open, setOpen] = useState(false);
  const [data, setData] = useState<Explanation | null>(memo.get(key) ?? null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const load = async () => {
    if (memo.has(key)) return setData(memo.get(key)!);
    setLoading(true);
    setError(null);
    try {
      const res = await fetch("/api/explain", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ situationId, label }),
      });
      const body = await res.json().catch(() => null);
      if (!res.ok) throw new Error(body?.error ?? `HTTP ${res.status}`);
      memo.set(key, body.explanation);
      setData(body.explanation);
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err));
    } finally {
      setLoading(false);
    }
  };

  return (
    <>
      <button
        type="button"
        className="explain-btn"
        aria-label={`Why this matters: ${label}`}
        title="Why this matters"
        onClick={() => {
          setOpen(true);
          if (!data) void load();
        }}
      >
        <Information size={16} aria-hidden />
      </button>
      <Modal open={open} passiveModal size="sm" modalLabel="Why this matters" modalHeading={label.charAt(0).toUpperCase() + label.slice(1)} onRequestClose={() => setOpen(false)}>
        {loading && <InlineLoading description="Generating explanation…" />}
        {error && <InlineNotification kind="error" lowContrast hideCloseButton title={error} />}
        {data && (
          <div className="explain">
            <p>{data.why}</p>
            {data.guideline && (
              <p className="explain__guideline">
                Guideline:{" "}
                <a href={data.guideline.url} target="_blank" rel="noopener noreferrer">
                  {data.guideline.title} <Launch size={12} aria-hidden />
                </a>
              </p>
            )}
            <p className="explain__note muted">General background generated by AI, not a statement about this patient.</p>
          </div>
        )}
      </Modal>
    </>
  );
}
